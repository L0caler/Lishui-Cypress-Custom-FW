/* ------------------------------------------------------------------------- *
 * ISSP vectors
 *
 * Every vector is a stream of 22 bit words:
 *
 *   100 aaaaaaaa dddddddd 111   write RAM[a] = d
 *   110 aaaaaaaa dddddddd 111   write REG[a] = d
 *   101 aaaaaaaa               read, target clocks the data back out
 *
 * RAM 0xF8..0xFE is the SROM parameter block (KEY1, KEY2, BLOCKID, POINTER,
 * CLOCK, ...).  REG[0xF0] selects the SROM function that the final
 * REG[0xFF] = 0x12 then runs: 0x01 read block, 0x02 write block, 0x03 erase
 * block, 0x04 protect block, 0x05 erase all, 0x06 table read, 0x07 checksum.
 * ------------------------------------------------------------------------- */

